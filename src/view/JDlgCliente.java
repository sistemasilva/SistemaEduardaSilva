    private void jBtnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBtnExcluirActionPerformed
        if (jTxtCodigo.getText().trim().isEmpty()) {
            Util.mensagem("Pesquise um cliente antes de Excluir");
            return;
        }

        if (Util.pergunta("Deseja excluir ?") == true) {
            ClienteDAO clienteDAO = new ClienteDAO();
            EcsCliente Ecscliente = viewBean();
            clienteDAO.delete(Ecscliente);
        }
        Util.limpar(jTxtCodigo, jTxtNome, jTxtEndereco, jTxtApelido, jFmtCpf, jFmtDataNascimento, jTxtNascionalidade, jTxtEmail, jFmtCelular, jFmtRg, jCboEstadoCivil, jCboSexo, jCboEscolaridade, jTxtProfissao);
    }//GEN-LAST:event_jBtnExcluirActionPerformed

