    public void beanView(EcsCliente clientes) {
        jTxtCodigo.setText(Util.intToStr(clientes.getIdecsCliente()));
        jTxtNome.setText(clientes.getEcsNomeCliente());
        jTxtEndereco.setText(clientes.getEcsEndereco());
        jTxtApelido.setText(clientes.getEcsApelido());
        jFmtCpf.setText(clientes.getEcsCpf());
        jTxtEmail.setText(clientes.getEcsEmail());
        jFmtCelular.setText(clientes.getEcsCelular());
        jFmtRg.setText(clientes.getEcsRg());
        jTxtNascionalidade.setText(clientes.getEcsNacionalidade());
        jFmtDataNascimento.setText(Util.dateToStr(clientes.getEcsDataNasc()));
        jTxtProfissao.setText(clientes.getEcsProfissao());
        jCboEstadoCivil.setSelectedIndex(clientes.getEcsEstadoCivil());
        jCboSexo.setSelectedIndex(clientes.getEcsSexo());
        jCboEscolaridade.setSelectedIndex(clientes.getEcsEscolaridade());

    }

    public EcsCliente viewBean() {
        EcsCliente Ecscliente = new EcsCliente();
        int cod = Util.strToInt(jTxtCodigo.getText());
        Ecscliente.setIdecsCliente(cod);
        Ecscliente.setEcsNomeCliente(jTxtNome.getText());
        Ecscliente.setEcsEndereco(jTxtEndereco.getText());
        Ecscliente.setEcsApelido(jTxtApelido.getText());
        Ecscliente.setEcsCpf(jFmtCpf.getText());
        Ecscliente.setEcsRg(jFmtRg.getText());
        Ecscliente.setEcsEmail(jTxtEmail.getText());
        Ecscliente.setEcsCelular(jFmtCelular.getText());
        Ecscliente.setEcsNacionalidade(jTxtNascionalidade.getText());
        Ecscliente.setEcsProfissao(jTxtProfissao.getText());
        Ecscliente.setEcsDataNasc(Util.strToDate(jFmtDataNascimento.getText()));
        Ecscliente.setEcsEstadoCivil(jCboEstadoCivil.getSelectedIndex());
        Ecscliente.setEcsSexo(jCboSexo.getSelectedIndex());
        Ecscliente.setEcsEscolaridade(jCboEscolaridade.getSelectedIndex());

        return Ecscliente;
    }

