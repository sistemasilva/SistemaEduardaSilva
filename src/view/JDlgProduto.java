    public void beanView(EcsProduto produto) {
        jTxtCodigo.setText(Util.intToStr(produto.getIdecsProduto()));
        jTxtNome.setText(produto.getEcsNome());
        jTxtDescricao.setText(produto.getEcsDescricao());
        jTxtCategoria.setText(produto.getEcsCategoria());
        jTxtQuantidade.setText(Util.intToStr(produto.getEcsQuantidade()));
        jFmtValorUnitário.setText(Util.doubleToStr(produto.getEcsValorUnitario()));
        jFmtAnoFabricacao.setText(Util.dateToStr(produto.getEcsAnoFabricacao()));
    }

    public EcsProduto viewBean() {
        EcsProduto Ecsproduto = new EcsProduto();
        int cod = Util.strToInt(jTxtCodigo.getText());
        Ecsproduto.setIdecsProduto(cod);
        Ecsproduto.setEcsNome(jTxtNome.getText());
        Ecsproduto.setEcsDescricao(jTxtDescricao.getText());
        Ecsproduto.setEcsCategoria(jTxtCategoria.getText());
        int quantidade = Util.strToInt(jTxtQuantidade.getText());
        Ecsproduto.setEcsQuantidade(quantidade);
        Ecsproduto.setEcsValorUnitario(Util.strToDouble(jFmtValorUnitário.getText()));
        Ecsproduto.setEcsAnoFabricacao(Util.strToDate(jFmtAnoFabricacao.getText()));
        return Ecsproduto;
    }

