    private void jBtnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBtnConfirmarActionPerformed
        ProdutoDAO produtoDAO = new ProdutoDAO();
        EcsProduto Ecsproduto = viewBean();
        if (incluir == true) {
            produtoDAO.insert(Ecsproduto);

        } else {
            produtoDAO.update(Ecsproduto);
        }
        Util.habilitar(false, jBtnConfirmar, jBtnCancelar, jTxtCodigo, jTxtNome, jTxtDescricao, jFmtAnoFabricacao, jTxtQuantidade, jTxtCategoria, jFmtValorUnitário);
        Util.habilitar(true, jBtnIncluir, jBtnExcluir, jBtnAlterar, jBtnPesquisar);
        Util.limpar(jTxtCodigo, jTxtNome, jTxtDescricao, jFmtAnoFabricacao, jTxtQuantidade, jTxtCategoria, jFmtValorUnitário);
    }//GEN-LAST:event_jBtnConfirmarActionPerformed

