    private void jBtnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBtnExcluirActionPerformed
        if (jTxtCodigo.getText().trim().isEmpty()) {
            Util.mensagem("Pesquise um produto antes de Excluir");
            return;
        }

        if (Util.pergunta("Deseja excluir ?") == true) {
            ProdutoDAO produtoDAO = new ProdutoDAO();
            EcsProduto Ecsproduto = viewBean();
            produtoDAO.delete(Ecsproduto);
        }
        Util.limpar(jTxtCodigo, jTxtNome, jTxtDescricao, jFmtAnoFabricacao, jTxtQuantidade, jTxtCategoria, jFmtValorUnitário);
    }//GEN-LAST:event_jBtnExcluirActionPerformed

